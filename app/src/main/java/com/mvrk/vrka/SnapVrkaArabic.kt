    private val ordered = phrases.entries.sortedByDescending { it.key.length }

    fun text(value: String): String {
        if (value.isEmpty()) return value
        phrases[value]?.let { return it }
        if (!value.any { it in 'A'..'Z' || it in 'a'..'z' }) return value
        if (value.startsWith("http://") || value.startsWith("https://") || value.startsWith("content://")) return value
        if (value.startsWith("--") || value.startsWith("-f ") || value.contains("yt-dlp ")) return value
        var result = value
        for ((english, arabic) in ordered) {
            if (english.length >= 4 && english in result) {
                result = result.replace(english, arabic)
            }
        }
        return result
    }

    fun containsArabic(value: String): Boolean = value.any { it in '\u0600'..'\u06FF' }

    fun knownPhraseCount(): Int = phrases.size
